def _card_rows(conn: sqlite3.Connection, oracle_ids: list[str],
               fmt: str | None = None) -> dict[str, Any]:
    """Cheap fields for the candidate cards.

    Legality is read with json_extract from ONE printing, not MIN(raw) across
    all of them: MIN over a text column reads every value, and pulling the full
    Scryfall blob for 200 cards moved a megabyte of JSON to answer a
    one-field question."""
    if not oracle_ids:
        return {}
    legal_expr = "NULL AS legality"
    if fmt:
        legal_expr = ("(SELECT json_extract(c5.raw, '$.legalities.' || ?1) "
                      " FROM cards c5 WHERE c5.oracle_id = c.oracle_id "
                      "   AND c5.digital = 0 LIMIT 1) AS legality")

    out: dict[str, Any] = {}
    for start in range(0, len(oracle_ids), 400):
        chunk = oracle_ids[start:start + 400]
        params: list[Any] = ([fmt.lower()] if fmt else []) + chunk
        marks = ",".join("?" * len(chunk))
        rows = conn.execute(f"""
            SELECT c.oracle_id,
                   MIN(c.name)            AS name,
                   MIN(c.mana_cost)       AS mana_cost,
                   MIN(c.mana_value)      AS mana_value,
                   MIN(c.type_line)       AS type_line,
                   MIN(c.oracle_text)     AS oracle_text,
                   MIN(c.color_identity)  AS color_identity,
                   MIN(c.price_usd)       AS price_usd,
                   (SELECT c8.id FROM cards c8
                     WHERE c8.oracle_id = c.oracle_id AND c8.digital = 0
                       AND c8.image_normal IS NOT NULL
                     ORDER BY c8.released_at DESC LIMIT 1) AS card_id,
                   {legal_expr},
                   (SELECT COUNT(*) FROM copies cp JOIN cards c2 ON c2.id=cp.card_id
                     WHERE c2.oracle_id = c.oracle_id) AS owned
            FROM cards c
            WHERE c.oracle_id IN ({marks}) AND c.digital = 0
            GROUP BY c.oracle_id""", params).fetchall()
        for r in rows:
            out[r["oracle_id"]] = r
    return out


def _legal(legality: str | None) -> bool:
    # An unknown legality is treated as legal: a missing field should not
    # quietly hide a card you own.
    return (legality or "legal") in ("legal", "restricted")


def _committed(conn: sqlite3.Connection) -> dict[str, list[str]]:
    """Which decks already use each card, so a suggestion can say so."""
    rows = conn.execute("""
        SELECT dc.oracle_id, d.name FROM deck_cards dc
        JOIN decks d ON d.id = dc.deck_id WHERE dc.wishlist = 0""").fetchall()
    out: dict[str, list[str]] = {}
    for r in rows:
        out.setdefault(r["oracle_id"], []).append(r["name"])
    return out


def _deck_members(conn: sqlite3.Connection, deck_id: int) -> set[str]:
    return {r[0] for r in conn.execute(
        "SELECT oracle_id FROM deck_cards WHERE deck_id=?", (deck_id,))}
